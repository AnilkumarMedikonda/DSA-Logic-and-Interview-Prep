
// ==================================================
// 07_Even_Stars.swift
// Print stars in even numbers (2, 4, 6, 8, 10)
// ==================================================

// Time Complexity: O(n²)
// Space Complexity: O(1)

import Foundation

let n = 10

// ==================================================
// Main Logic
// ==================================================

for i in 1...n {
    
    if i % 2 == 0 {
        
        for _ in 1...i {
            print("*", terminator: "")
        }
        
        print()
    }
}


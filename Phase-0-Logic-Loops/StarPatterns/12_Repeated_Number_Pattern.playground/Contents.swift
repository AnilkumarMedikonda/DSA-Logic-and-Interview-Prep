import UIKit
// ==================================================
// 12_Repeated_Number_Pattern.swift
// Print repeated number pattern
// ==================================================

// Time Complexity: O(n²)
// Space Complexity: O(1)

import Foundation

let n = 5

// ==================================================
// Main Logic
// ==================================================

for i in 1...n {
    for _ in 1...i {
        print(i, terminator: "")
    }
    print()
}

// ==================================================
// Output (n = 5)
// ==================================================

// 1
// 22
// 333
// 4444
// 55555


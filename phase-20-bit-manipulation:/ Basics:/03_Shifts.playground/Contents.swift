// ============================================================
// MARK: - Left Shift <<
// ============================================================
//
// << means move bits to the LEFT.
//
// << 1 → multiply by 2
// << 2 → multiply by 4
// << 3 → multiply by 8
//
// Example:
//
// 3 = 0011
//
// 3 << 1
//
// 0011
// 0110
//
// 0110 = 6
//
// Therefore:
//
// 3 << 1 = 6
//

let number = 3

print("Left Shift")

print("3 << 1 =", number << 1)
print("3 << 2 =", number << 2)
print("3 << 3 =", number << 3)


// ============================================================
// MARK: - Left Shift Examples
// ============================================================

print("\nLeft Shift Examples")

print("5 << 1 =", 5 << 1)
print("5 << 2 =", 5 << 2)
print("5 << 3 =", 5 << 3)

print("10 << 1 =", 10 << 1)
print("10 << 2 =", 10 << 2)


// ============================================================
// MARK: - Right Shift >>
// ============================================================
//
// >> means move bits to the RIGHT.
//
// >> 1 → divide by 2
// >> 2 → divide by 4
// >> 3 → divide by 8
//
// Example:
//
// 10 = 1010
//
// 10 >> 1
//
// 1010
// 0101
//
// 0101 = 5
//
// Therefore:
//
// 10 >> 1 = 5
//

let value = 10

print("\nRight Shift")

print("10 >> 1 =", value >> 1)
print("10 >> 2 =", value >> 2)


// ============================================================
// MARK: - Right Shift Examples
// ============================================================

print("\nRight Shift Examples")

print("20 >> 1 =", 20 >> 1)
print("20 >> 2 =", 20 >> 2)
print("20 >> 3 =", 20 >> 3)

print("16 >> 1 =", 16 >> 1)
print("16 >> 2 =", 16 >> 2)


// ============================================================
// MARK: - Binary Examples
// ============================================================

print("\nBinary Examples")

// 3 = 0011
//
// 3 << 1
//
// 0011 → 0110
//
// 3 << 2
//
// 0011 → 0110 → 1100

print("3       =", String(3, radix: 2))
print("3 << 1  =", String(3 << 1, radix: 2))
print("3 << 2  =", String(3 << 2, radix: 2))


// 10 = 1010
//
// 10 >> 1
//
// 1010 → 0101
//
// 10 >> 2
//
// 1010 → 0101 → 0010

print("\n10       =", String(10, radix: 2))
print("10 >> 1  =", String(10 >> 1, radix: 2))
print("10 >> 2  =", String(10 >> 2, radix: 2))


